test('authorship filtering excludes complete machine envelopes and preserves remaining text', () => {
  const instructions = '# AGENTS.md instructions for /work/demo\n\n<INSTRUCTIONS>\nRun focused checks.\n</INSTRUCTIONS>';
  assert.equal(extractGenuineUserText(instructions), null);
  assert.equal(extractGenuineUserText('<agents_instructions>Machine policy.</agents_instructions>'), null);
  const authored = 'Fix this example:\n```python\nif True:\n    print("hello")\n```';
  assert.equal(extractGenuineUserText(`<system-reminder>Machine policy.</system-reminder>\n${authored}`), authored);
  assert.equal(extractGenuineUserText(`${authored}\n<environment_context>cwd=/work/demo</environment_context>`), authored);
  assert.equal(extractGenuineUserText(`<system-reminder/>\n<timestamp>2026-07-03</timestamp>\n${authored}`), authored);
  const caveat = 'Caveat: The messages below were generated by the user while running local commands.';
  assert.equal(extractGenuineUserText(`<local-command-caveat>${caveat}</local-command-caveat>`), null);
  assert.equal(classifyAnalysisRole({ type: 'user', isMeta: true, message: { role: 'user', content: caveat } }).role, null);
});

test('a trailing wrapper never consumes earlier quoted wrappers or intervening user constraints', () => {
  for (const tag of ['system-reminder', 'timestamp']) {
    const authored = `Explain these log lines:\n<${tag}>one</${tag}>\nDo not execute anything.`;
    assert.equal(extractGenuineUserText(`${authored}\n<${tag}>two</${tag}>`), authored);
  }
});

test('user content blocks preserve leading and trailing whitespace while whitespace-only content stays empty', () => {
  const raw = '\n  Please keep this whitespace.\n\n';
  assert.equal(genuineUserTextFromContent(raw), raw);
  assert.equal(genuineUserTextFromContent([{ type: 'input_text', text: raw }]), raw);
  assert.equal(genuineUserTextFromContent(' \n\t'), null);
});

test('semantic projection preserves genuine source quotations and rejects whitespace-rewritten evidence', async () => {
  const root = await mkdtemp(join(tmpdir(), 'agent-insight-authorship-verbatim-'));
  const file = join(root, 'authored.jsonl');
  const texts = [
    '请只更新约定的排版。\nAGENTS.md 是仓库的协作约定。',
    '请检查下面的引用：\n```markdown\n# AGENTS.md\nKeep tests focused.\n```',
    '请修复下面的 Python：\n```python\nif True:\n    print("hello")\n```'
  ];
  await writeFile(file, [
    { type: 'response_item', payload: { type: 'message', role: 'system', content: [{ type: 'input_text', text: 'Machine policy.' }] } },
    { type: 'response_item', payload: { type: 'message', role: 'developer', content: [{ type: 'input_text', text: 'Injected instructions.' }] } },
    ...texts.map((text) => ({ type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text }] } }))
  ].map(JSON.stringify).join('\n'));
  const input = await extractAnalysisInput(file, 'codex');
  assert.deepEqual(input.messages.map((message) => message.text), texts);
  assert.equal(input.userMessageCount, 3);
  const strength = (quotation) => ({
    habit: 'Provide a concrete example.', explanation: 'The request includes the relevant code.',
    quotations: [quotation], locators: [{ message_indexes: [3] }]
  });
  const quote = 'if True:\n    print("hello")';
  assert.equal(validateSessionAuditResult({ findings: [], strengths: [strength(quote)] }, input).strengths[0].quotations[0], quote);
  assert.throws(() => validateSessionAuditResult({ findings: [], strengths: [strength('if True:\n print("hello")')] }, input), /fabricated quotation/);
});

